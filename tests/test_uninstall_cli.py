class TestFullUninstall:
    def test_restores_hermes_files_and_removes_mordred(
        self, installed: Installed, capsys: pytest.CaptureFixture[str]
    ) -> None:
        home = installed.home
        rc = run_uninstall(installed.context(), UninstallOptions(yes=True))
        out = capsys.readouterr().out

        assert rc == 0, out
        # a. plaintext is back, byte for byte.
        assert (home / ".env").read_bytes() == installed.before[".env"]
        for name in _MEMORIES:
            assert (home / "memories" / name).read_bytes() == installed.before[f"memories/{name}"]
        assert not _marker_path(home).exists()
        assert not memory_marker_path(home).exists()
        # b. config.yaml has nothing of Mordred's left.
        assert _yaml(home / "config.yaml") == _yaml_text(installed.before["config.yaml"])
        assert list(home.glob("config.yaml.mordred-uninstall-*.bak"))
        assert not (home / "plugins" / "mordred").exists()
        assert not (home / ".env.lock").exists()
        saved = (home / "mordred" / "uninstall" / "env-removed-20260101-000000.env").read_text(encoding="utf-8")
        assert "HERMES_MEMORY_KEY=" in saved and "MORDRED_MULLVAD_ACCOUNT=1234567890" in saved
        # c. the installer's launcher is gone.
        assert not (installed.user_home / ".local" / "bin" / "hermes-mordred").exists()
        # d. the package is uninstalled from Hermes's environment, last.
        assert installed.runner.uninstalls == [
            [
                str(home / "tools" / "uv-0.1.0" / "uv"),
                "pip",
                "uninstall",
                "--python",
                str(installed.hermes_python),
                "hermes-mordred",
            ]
        ]
        # e. data is kept and listed.
        assert installed.root.is_dir()
        assert "Kept (not deleted)" in out and str(installed.root) in out

    def test_config_yaml_is_byte_identical(self, installed: Installed) -> None:
        assert run_uninstall(installed.context(), UninstallOptions(yes=True)) == 0
        assert (installed.home / "config.yaml").read_bytes() == installed.before["config.yaml"]

    def test_unlocks_the_vault_once(self, installed: Installed) -> None:
        installed.backend.calls.clear()
        assert run_uninstall(installed.context(), UninstallOptions(yes=True)) == 0
        assert [call for call in installed.backend.calls if call[0] == "ecdh"] == [
            ("ecdh", _identity.vault_identity(installed.root))
        ]

    def test_second_run_changes_nothing(self, installed: Installed, capsys: pytest.CaptureFixture[str]) -> None:
        assert run_uninstall(installed.context(), UninstallOptions(yes=True)) == 0
        after_first = _snapshot(installed.home)
        backups = sorted(installed.home.glob("config.yaml.mordred-uninstall-*.bak"))
        capsys.readouterr()

        assert run_uninstall(installed.context(stamp="20260102-000000"), UninstallOptions(yes=True)) == 0

        assert "nothing to do" in capsys.readouterr().out
        assert _snapshot(installed.home) == after_first
        assert sorted(installed.home.glob("config.yaml.mordred-uninstall-*.bak")) == backups
        assert len(installed.runner.uninstalls) == 1

    def test_dry_run_changes_nothing(self, installed: Installed, capsys: pytest.CaptureFixture[str]) -> None:
        tree_before = _tree(installed.home)

        assert run_uninstall(installed.context(), UninstallOptions(dry_run=True)) == 0

        out = capsys.readouterr().out
        assert _tree(installed.home) == tree_before
        assert installed.runner.uninstalls == []
        assert "Dry run: nothing was changed." in out
        for expected in ("config: vault-managed", "memory: 2 sealed", "env: vault-managed", "config.yaml is sealed"):
            assert expected in out


def _yaml_text(raw: bytes) -> object:
    return YAML(typ="safe").load(raw.decode("utf-8"))


def _tree(root: Path) -> dict[str, bytes | None]:
    return {
        str(path.relative_to(root)): (path.read_bytes() if path.is_file() else None) for path in sorted(root.rglob("*"))
    }


