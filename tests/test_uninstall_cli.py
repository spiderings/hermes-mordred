def _hermes_env(home: Path) -> Path:
    """A virtualenv-shaped Hermes environment holding the console script."""
    bin_dir = home / "hermes-agent" / "venv" / "bin"
    bin_dir.mkdir(parents=True)
    (home / "hermes-agent" / "venv" / "pyvenv.cfg").write_text("home = /usr/bin\n", encoding="utf-8")
    for name in ("python3", "hermes-mordred"):
        (bin_dir / name).write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        (bin_dir / name).chmod(0o755)
    uv = home / "tools" / "uv-0.1.0" / "uv"
    uv.parent.mkdir(parents=True)
    uv.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    uv.chmod(0o755)
    return bin_dir / "python3"


