@dataclass
class FakeRunner:
    """Stands in for uv / codesign / the Hermes launcher; records every call."""

    installed: set[str] = field(default_factory=lambda: {"hermes-mordred"})
    calls: list[list[str]] = field(default_factory=list)
    uninstall_rc: int = 0
    codesign: str = ""

    def __call__(self, argv: Sequence[str]) -> subprocess.CompletedProcess[str]:
        argv = list(argv)
        self.calls.append(argv)
        rc, out, err = 64, "", ""
        if argv[1:3] == ["pip", "show"]:
            rc = 0 if argv[-1] in self.installed else 1
        elif argv[1:3] == ["pip", "uninstall"]:
            rc = self.uninstall_rc
            if rc == 0:
                self.installed.clear()
            out = "Uninstalled 1 package"
        elif argv[0] == "codesign":
            rc, err = 0, self.codesign
        return subprocess.CompletedProcess(argv, rc, out, err)

    @property
    def uninstalls(self) -> list[list[str]]:
        return [call for call in self.calls if call[1:3] == ["pip", "uninstall"]]


@dataclass
class Installed:
    home: Path
    root: Path
    user_home: Path
    backend: FakeBackend
    store: FakeAnchorStore
    runner: FakeRunner
    hermes_python: Path
    before: dict[str, bytes]

    def context(self, **overrides: object) -> UninstallContext:
        values: dict[str, object] = {
            "home": self.home,
            "vault_root": self.root,
            "user_home": self.user_home,
            "platform": "darwin",
            "backend": self.backend,
            "store": self.store,
            "which": lambda _name: None,
            "runner": self.runner,
            "stamp": "20260101-000000",
            "interactive": False,
            "gateways": lambda _home: [],
            "telegram_forget": lambda: 0,
            "keyvault_reset": lambda _home: 0,
        }
        values.update(overrides)
        return UninstallContext(**values)  # type: ignore[arg-type]


def _snapshot(home: Path) -> dict[str, bytes]:
    files = {"config.yaml": (home / "config.yaml").read_bytes(), ".env": (home / ".env").read_bytes()}
    for name in _MEMORIES:
        files[f"memories/{name}"] = (home / "memories" / name).read_bytes()
    return files


def _yaml(path: Path) -> object:
    return YAML(typ="safe").load(path.read_text(encoding="utf-8"))


