class _TypedPrompt:
    def __init__(self, text: str) -> None:
        self.text = text
        self.asked: list[str] = []

    def ask_bool(self, label: str, default: bool, *, description: str | None = None) -> bool:
        self.asked.append(label)
        return True

    def ask_text(self, label: str, default: str = "", *, description: str | None = None) -> str:
        self.asked.append(label)
        return self.text


class TestEraseEncrypted:
    def test_erases_without_decrypting_or_unlocking(
        self, installed: Installed, capsys: pytest.CaptureFixture[str]
    ) -> None:
        home = installed.home
        installed.backend.calls.clear()
        prompt = _TypedPrompt(uninstall_cli.PURGE_PHRASE)
        ctx = installed.context(prompt_io=prompt, telegram_forget=lambda: 0, keyvault_reset=lambda _home: 0)

        rc = run_uninstall(ctx, UninstallOptions(yes=True, erase_encrypted=True))

        out = capsys.readouterr().out
        assert rc == 0, out
        assert "ERASE encrypted data WITHOUT decrypting" in out
        assert len(prompt.asked) == 1  # the typed "delete my data"
        # Nothing was decrypted: no vault unlock, no plaintext written back.
        assert not [call for call in installed.backend.calls if call[0] == "ecdh"]
        assert not (home / ".env").exists() and not (home / "config.yaml").exists()
        assert not any((home / "memories" / name).exists() for name in _MEMORIES)
        # Mordred and all its data are gone.
        assert not (home / "mordred").exists()
        assert not (home / "plugins" / "mordred").exists()
        assert installed.runner.uninstalls

    def test_erase_needs_the_typed_phrase(self, installed: Installed) -> None:
        ctx = installed.context(prompt_io=_TypedPrompt("yes"))
        assert run_uninstall(ctx, UninstallOptions(yes=True, erase_encrypted=True)) == 1
        assert all(is_sealed((installed.home / "memories" / n).read_bytes()) for n in _MEMORIES)
        assert (installed.home / "mordred" / "vault").is_dir()


class TestPurge:
    def test_deletes_data_after_typed_confirmation(self, installed: Installed) -> None:
        telegram = installed.home / "mordred" / "telegram"
        telegram.mkdir(parents=True)
        (telegram / "credentials.sealed").write_bytes(b"MTC1")
        (installed.home / "mordred" / "keyvault").mkdir()
        events: list[str] = []

        def telegram_forget() -> int:
            events.append("telegram")
            return 0

        def keyvault_reset(_home: Path) -> int:
            events.append("keyvault")
            return 0

        prompt = _TypedPrompt(uninstall_cli.PURGE_PHRASE)
        ctx = installed.context(prompt_io=prompt, telegram_forget=telegram_forget, keyvault_reset=keyvault_reset)

        rc = run_uninstall(ctx, UninstallOptions(yes=True, purge_data=True))

        assert rc == 0
        assert events == ["telegram", "keyvault"]
        assert len(prompt.asked) == 1  # --yes skips the plain question, never the typed one
        assert not (installed.home / "mordred").exists()
        label = _identity.vault_identity(installed.root)
        assert installed.store.read(label) is None
        assert ("delete", label) in installed.backend.calls
        assert (installed.home / ".env").read_bytes() == installed.before[".env"]

    def test_undeletable_device_key_is_reported_with_manual_steps(
        self, installed: Installed, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        def refuse(_key_id: str) -> None:
            raise RuntimeError("owner ACL")

        monkeypatch.setattr(installed.backend, "delete_enclave_key", refuse)
        ctx = installed.context(prompt_io=_TypedPrompt(uninstall_cli.PURGE_PHRASE))

        assert run_uninstall(ctx, UninstallOptions(yes=True, purge_data=True)) == 0

        err = capsys.readouterr().err
        assert "Keychain Access" in err and "mordred-hermes.wrsw." in err
        assert not (installed.home / "mordred").exists()

    def test_wrong_phrase_changes_nothing(self, installed: Installed) -> None:
        rc = run_uninstall(
            installed.context(prompt_io=_TypedPrompt("yes")), UninstallOptions(yes=True, purge_data=True)
        )

        assert rc == 1
        assert installed.root.is_dir()
        assert not (installed.home / ".env").exists()
        assert installed.runner.uninstalls == []

    def test_keyvault_reset_failure_keeps_the_data(self, installed: Installed) -> None:
        (installed.home / "mordred" / "keyvault").mkdir()
        ctx = installed.context(prompt_io=_TypedPrompt(uninstall_cli.PURGE_PHRASE), keyvault_reset=lambda _home: 1)

        assert run_uninstall(ctx, UninstallOptions(yes=True, purge_data=True)) == 1
        assert (installed.home / "mordred" / "keyvault").is_dir()
        assert installed.runner.uninstalls == []


