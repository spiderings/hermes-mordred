class TestHermesEnvDetection:
    def test_managed_launcher_reports_its_environment(self, tmp_path: Path) -> None:
        home = tmp_path / "hermes"
        env_root = tmp_path / "installs" / "env" / "venv"
        (env_root / "bin").mkdir(parents=True)
        (env_root / "pyvenv.cfg").write_text("", encoding="utf-8")
        python = env_root / "bin" / "python"
        python.write_text("", encoding="utf-8")
        python.chmod(0o755)
        launcher = home / "hermes-agent" / ".hermes" / "bin" / "hermes"
        launcher.parent.mkdir(parents=True)
        launcher.write_text("#!/bin/sh\nexec /opt/python3 -I -c 'boot' \"$@\"\n", encoding="utf-8")
        launcher.chmod(0o755)
        site = f"sys.path = [\n    '{env_root}/lib/python3.14/site-packages',\n]\n"

        def runner(argv: Sequence[str]) -> subprocess.CompletedProcess[str]:
            if list(argv[1:]) == ["--run-module", "site"]:
                return subprocess.CompletedProcess(list(argv), 0, site, "")
            return subprocess.CompletedProcess(list(argv), 1, "", "")

        env = detect_hermes_env(home, which=lambda _name: None, runner=runner)

        assert env.launcher == launcher
        assert env.python == python
        assert env.problem == "uv was not found (not on PATH, not under <home>/tools)"

    def test_foreign_launcher_is_kept_and_symlink_to_console_script_removed(self, tmp_path: Path) -> None:
        user_home = tmp_path / "user"
        bin_dir = user_home / ".local" / "bin"
        bin_dir.mkdir(parents=True)
        python = tmp_path / "venv" / "bin" / "python3"
        env = HermesEnv(launcher=bin_dir / "hermes", python=python, uv=None, installed=())
        (bin_dir / "hermes-mordred").symlink_to(python.parent / "hermes-mordred")

        findings = classify_launchers(env, user_home=user_home)
        assert [(f.path, f.remove) for f in findings] == [(bin_dir / "hermes-mordred", True)]

        (bin_dir / "hermes-mordred").unlink()
        (bin_dir / "hermes-mordred").write_text("#!/bin/sh\necho mine\n", encoding="utf-8")
        assert [f.remove for f in classify_launchers(env, user_home=user_home)] == [False]

    def test_only_the_mordred_built_sekey_helper_is_removable(self, tmp_path: Path) -> None:
        helper = tmp_path / ".local" / "bin" / "mordred-hermes-sekey"
        helper.parent.mkdir(parents=True)
        helper.write_bytes(b"\xcf\xfa")
